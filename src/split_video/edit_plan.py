def _field_schema(f: Field) -> dict[str, Any]:
    body: dict[str, Any] = {"type": [f.type, "null"] if f.nullable else f.type, "description": f.description}
    if f.const is not None:
        body["const"] = f.const
    if f.enum is not None:
        body["enum"] = list(f.enum)
    for key, value in (
        ("minimum", f.minimum),
        ("maximum", f.maximum),
        ("exclusiveMinimum", f.exclusive_minimum),
        ("pattern", f.pattern),
        ("maxLength", f.max_length),
        ("default", f.default),
    ):
        if value is not None:
            body[key] = value
    return body


def _object_schema(fields: tuple[Field, ...]) -> dict[str, Any]:
    return {
        "type": "object",
        "additionalProperties": False,
        "required": [f.name for f in fields if f.required],
        "properties": {f.name: _field_schema(f) for f in fields},
    }


def schema() -> dict[str, Any]:
    """The JSON Schema (draft 2020-12) of a version 1 plan, built from the field tables."""
    clip = _object_schema(CLIP_FIELDS)
    clip["allOf"] = [
        {
            "if": {"properties": {"kind": {"const": "text"}}, "required": ["kind"]},
            "then": {"required": ["text", "out"]},
            "else": {"anyOf": [{"required": ["asset"]}, {"required": ["source"]}]},
        }
    ]
    track = _object_schema(TRACK_FIELDS)
    track["properties"]["clips"] = {**track["properties"]["clips"], "items": {"$ref": "#/$defs/clip"}}
    top = _object_schema(TOP_FIELDS)
    top["properties"]["tracks"] = {
        **top["properties"]["tracks"],
        "minItems": 1,
        "maxItems": MAX_TRACKS,
        "items": {"$ref": "#/$defs/track"},
    }
    return {
        "$schema": SCHEMA_URI,
        "$id": SCHEMA_ID,
        "title": "split-video edit plan, schema_version 1",
        "description": (
            "One JSON document that creates or replaces a whole timeline project atomically. Strict: unknown "
            "fields are rejected. Constraints this schema cannot express (asset ids exist, in/out within the asset, "
            f"no overlaps, crossfade room, at most {MAX_CLIPS} clips in total) are checked by the server and "
            "reported with stable codes; see docs/edit-plan.md."
        ),
        **top,
        "$defs": {"track": track, "clip": clip},
    }


def schema_json() -> str:
    """`schema()` as the exact text committed to docs/schemas/edit-plan.v1.schema.json."""
    return json.dumps(schema(), indent=2, sort_keys=True) + "\n"


# --- the report ----------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class PlanIssue:
    path: str  # JSON pointer into the plan, e.g. /tracks/0/clips/3/out
    code: str  # stable and namespaced, e.g. plan.clip.out_of_range
    message: str
    hint: str = ""

    def to_dict(self) -> dict[str, str]:
        return {"path": self.path, "code": self.code, "message": self.message, "hint": self.hint}


@dataclass
class PlanReport:
    errors: list[PlanIssue] = field(default_factory=list)
    warnings: list[PlanIssue] = field(default_factory=list)
    plan_hash: str | None = None

    @property
    def ok(self) -> bool:
        return not self.errors

    def error(self, path: str, code: str, message: str, hint: str = "") -> None:
        self.errors.append(PlanIssue(path, code, message, hint))

    def warn(self, path: str, code: str, message: str, hint: str = "") -> None:
        self.warnings.append(PlanIssue(path, code, message, hint))

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "errors": [e.to_dict() for e in self.errors],
            "warnings": [w.to_dict() for w in self.warnings],
            "plan_hash": self.plan_hash,
        }


class PlanInvalidError(TimelineError):
    """The plan has problems; nothing was created or changed. `report` lists every one of them."""

    def __init__(self, report: PlanReport) -> None:
        self.report = report
        super().__init__(compact(report))


def compact(report: PlanReport) -> str:
    """The report as compact JSON (what an MCP tool error carries)."""
    return json.dumps({"error": "plan_invalid", **report.to_dict()}, separators=(",", ":"))


# --- versions ----------------------------------------------------------------------------------------------------


# `MIGRATIONS[n]` turns a version n document into a version n+1 one. There is nothing below version 1 today;
# the table is the seam a version 2 uses to keep accepting version 1 plans.
MIGRATIONS: dict[int, Callable[[dict[str, Any]], dict[str, Any]]] = {}


class PlanVersionError(ValueError):
    """The plan's `schema_version` can't be used; `code` is the plan error code to report."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def migrate_plan(doc: dict[str, Any]) -> dict[str, Any]:
    """`doc` brought up to `SCHEMA_VERSION` (a new dict). `PlanVersionError` if its version is not an integer, is newer
    than this server knows, or is older than the oldest version with a migration."""
    version = doc.get("schema_version")
    if isinstance(version, bool) or not isinstance(version, int):
        raise PlanVersionError("plan.schema_version.invalid", "schema_version must be an integer")
    if version > SCHEMA_VERSION:
        raise PlanVersionError(
            "plan.schema_version.unsupported",
            f"schema_version {version} is newer than this server supports ({SCHEMA_VERSION})",
        )
    doc = copy.deepcopy(doc)
    while version < SCHEMA_VERSION:
        step = MIGRATIONS.get(version)
        if step is None:
            raise PlanVersionError(
                "plan.schema_version.unsupported",
                f"schema_version {version} is no longer supported (the oldest accepted is {_oldest()})",
            )
        doc = step(doc)
        version += 1
        doc["schema_version"] = version
    return doc


def _oldest() -> int:
    return min([*MIGRATIONS, SCHEMA_VERSION])


def canonical_hash(doc: dict[str, Any]) -> str:
    """sha256 of the plan's canonical JSON (sorted keys, no spaces), ignoring `meta`, which is only a note."""
    body = {k: v for k, v in doc.items() if k != "meta"}
    text = json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(text.encode()).hexdigest()


# --- validation --------------------------------------------------------------------------------------------------


def _pointer(*parts: str | int) -> str:
    return "".join("/" + str(p).replace("~", "~0").replace("/", "~1") for p in parts)


def _is_number(value: Any) -> bool:
    return isinstance(value, int | float) and not isinstance(value, bool) and math.isfinite(value)


_TYPE_CHECKS: dict[str, Callable[[Any], bool]] = {
    "string": lambda v: isinstance(v, str),
    "number": _is_number,
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
    "object": lambda v: isinstance(v, dict),
    "array": lambda v: isinstance(v, list),
}


def _check_object(obj: dict[str, Any], fields: tuple[Field, ...], path: str, report: PlanReport) -> dict[str, Any]:
    """Check `obj` against `fields`: unknown names, required ones, types, enums, ranges, patterns and lengths.
    Returns the fields that are present and well-formed (problems are in `report`)."""
    known = {f.name: f for f in fields}
    allowed = ", ".join(known)
    good: dict[str, Any] = {}
    for key in obj:
        if key not in known:
            report.error(
                _pointer(*_split(path), key),
                "plan.field.unknown",
                f"unknown field {key!r}",
                f"allowed fields here: {allowed}. The schema is strict; see GET /api/v1/schemas/edit-plan.",
            )
    for f in fields:
        where = _pointer(*_split(path), f.name)
        if f.name not in obj:
            if f.required:
                report.error(where, "plan.field.required", f"missing required field {f.name!r}", f"add {f.name!r}")
            continue
        value = obj[f.name]
        if value is None and f.nullable:
            good[f.name] = None
            continue
        if not _TYPE_CHECKS[f.type](value):
            shown = "a non-finite number" if isinstance(value, float) else type(value).__name__
            report.error(where, "plan.field.type", f"{f.name!r} must be a {f.type}, not {shown}", f"send a {f.type}")
            continue
        if f.const is not None and value != f.const:
            report.error(where, "plan.field.value", f"{f.name!r} must be {f.const!r}", "")
            continue
        if f.enum is not None and value not in f.enum:
            report.error(
                where,
                "plan.field.enum",
                f"{f.name!r} must be one of {', '.join(f.enum)}, not {value!r}",
                f"use one of: {', '.join(f.enum)}",
            )
            continue
        if f.type in ("number", "integer") and _out_of_range(value, f):
            report.error(where, "plan.field.range", f"{f.name!r} {_range_text(f)}, not {value:g}", "")
            continue
        if f.pattern is not None and not re.match(f.pattern, value):
            report.error(
                where, "plan.field.pattern", f"{f.name!r} must look like {_pattern_hint(f)}, not {value!r}", ""
            )
            continue
        if f.max_length is not None and len(value) > f.max_length:
            report.error(
                where, "plan.field.length", f"{f.name!r} is longer than {f.max_length} characters", "shorten it"
            )
            continue
        good[f.name] = value
    return good


def _split(path: str) -> list[str]:
    return [p.replace("~1", "/").replace("~0", "~") for p in path.split("/")[1:]]


def _out_of_range(value: float, f: Field) -> bool:
    return (
        (f.minimum is not None and value < f.minimum)
        or (f.maximum is not None and value > f.maximum)
        or (f.exclusive_minimum is not None and value <= f.exclusive_minimum)
    )


def _range_text(f: Field) -> str:
    low = f.minimum if f.minimum is not None else f.exclusive_minimum
    word = "at least" if f.minimum is not None else "above"
    if low is not None and f.maximum is not None:
        return f"must be between {low:g} and {f.maximum:g}"
    if low is not None:
        return f"must be {word} {low:g}"
    return f"must be at most {f.maximum:g}"


def _pattern_hint(f: Field) -> str:
    return "#rrggbb" if f.name == "color" else f.pattern or ""


@dataclass
class _Item:
    """One clip of a track while the plan is being checked."""

    index: int
    clip: Clip | None = None  # None: the clip has a problem and is left out of the project
    duration: float | None = None  # known whenever in/out were usable, even if something else is wrong
    transition: str = "cut"
    fade: float = 0.0
    start: float | None = None


class _Context:
    def __init__(self, media: MediaStore, book: assets.AssetBook, report: PlanReport) -> None:
        self.media = media
        self.book = book
        self.report = report
        self.by_path: dict[str, assets.Asset] = {}
        for row in book.list():
            self.by_path[row.path] = row
            for copy_path in row.copies:
                self.by_path.setdefault(copy_path, row)

    def find_asset(self, clip: dict[str, Any], path: str) -> tuple[assets.Asset, str] | None:
        """The asset a media clip names (`asset` wins over `source`) and the path to store as its hint."""
        report = self.report
        asset_id, source = clip.get("asset"), clip.get("source")
        if asset_id is not None:
            if not assets.is_asset_id(asset_id):
                report.error(
                    path + "/asset",
                    "plan.asset.invalid_id",
                    f"{asset_id!r} is not an asset id (a_ followed by 16 hex digits)",
                    "use an id from list_assets",
                )
                return None
            row = self.book.get(asset_id)
            if row is None:
                report.error(
                    path + "/asset",
                    "plan.asset.unknown",
                    f"unknown asset {asset_id!r}",
                    "list_assets shows the known assets; scan_library registers new files",
                )
                return None
            if source is not None and self._resolve(source) not in (row.path, *row.copies):
                report.warn(
                    path + "/source",
                    "plan.clip.source_mismatch",
                    f"source {source!r} is not where asset {asset_id} lives ({row.path!r}); the asset wins",
                    "drop `source` or give the matching one",
                )
            return row, row.path
        if source is None:
            report.error(
                path,
                "plan.clip.media_source_missing",
                "a media clip needs an `asset` (or a `source` path that is already an asset)",
                "add an `asset` id from list_assets",
            )
            return None
        media_id = self._resolve(source)
        if media_id is None:
            report.error(
                path + "/source",
                "plan.source.outside_root",
                f"source {source!r} is outside the workspace",
                "use a path relative to the workspace root, or an asset id",
            )
            return None
        row = self.by_path.get(media_id)
        if row is None:
            report.error(
                path + "/source",
                "plan.source.unknown",
                f"{source!r} is not a known asset",
                "run scan_library (or `split-video library scan`) so the file becomes an asset, then use its id "
                "from list_assets",
            )
            return None
        return row, media_id

    def _resolve(self, source: str) -> str | None:
        try:
            return self.media.resolve(source)
        except MediaOutsideRootError:
            return None


def _generated_id(plan_hash: str, kind: str, *position: int, taken: set[str]) -> str:
    """An id derived from the plan's hash and the element's position: the same plan always gets the same ids."""
    salt = 0
    while True:
        text = f"{plan_hash}:{kind}:{'.'.join(map(str, position))}:{salt}"
        found = hashlib.sha256(text.encode()).hexdigest()[:8]
        if found not in taken:
            taken.add(found)
            return found
        salt += 1


def _compile(
    media: MediaStore,
    plan_doc: Any,
    store: ProjectStore | None,
    base_revision: int | None,
) -> tuple[PlanReport, Project | None, dict[str, Any]]:
    """Everything `validate_plan`, `build_timeline` and `apply_plan` need, in one pass: the report, the project (None
    unless the plan is valid) and the plan as a version 1 document. Reads the asset table and (with `store`) whether
    the project exists; writes nothing."""
    report = PlanReport()
    if not isinstance(plan_doc, dict):
        report.error("", "plan.document.not_object", "a plan must be a JSON object", 'send {"schema_version": 1, ...}')
        return report, None, {}
    version = plan_doc.get("schema_version")
    if version is None:
        report.error(
            "/schema_version", "plan.schema_version.missing", "missing required field 'schema_version'",
            f"add \"schema_version\": {SCHEMA_VERSION}",
        )  # fmt: skip
        doc = dict(plan_doc)
        doc["schema_version"] = SCHEMA_VERSION  # keep checking the rest as a current plan
    else:
        try:
            doc = migrate_plan(plan_doc)
        except PlanVersionError as exc:
            hint = (
                "send an integer"
                if exc.code.endswith("invalid")
                else f"write the plan as schema_version {SCHEMA_VERSION}; GET /api/v1/schemas/edit-plan has the format"
            )
            report.error("/schema_version", exc.code, str(exc), hint)
            return report, None, {}
        except Exception as exc:  # noqa: BLE001 - a migration is code too: report it, don't crash the call
            report.error(
                "/schema_version", "plan.schema_version.migration_failed", f"migrating the plan failed: {exc}", ""
            )
            return report, None, {}
    try:
        report.plan_hash = canonical_hash(doc)
    except (TypeError, ValueError):
        report.error(
            "",
            "plan.document.not_json",
            "the plan is not plain JSON data",
            "send only objects, arrays, strings, numbers, booleans and null",
        )
        return report, None, {}
    plan_hash = report.plan_hash

    top = _check_object(doc, TOP_FIELDS, "", report)
    name = top.get("project")
    if name is not None:
        try:
            timeline.validate_name(name)
        except TimelineError:
            report.error(
                "/project", "plan.project.name_invalid", f"invalid project name {name!r}",
                "use a plain name: no slashes, not starting with a dot",
            )  # fmt: skip
            name = None
    mode = top.get("mode", "create")
    effective_base = _effective_base_revision(top, base_revision, report)
    unconditional = top.get("replace_unconditionally", False)
    exists: bool | None = None
    if name is not None and store is not None:
        exists = store.timeline_exists(name)
    _check_mode(report, mode, effective_base, unconditional, name, exists, store)

    ctx_tracks = top.get("tracks")
    tracks_out: list[Track] = []
    if ctx_tracks is not None:
        with assets.open_book(media) as book:  # reads only; the book is saved on exit only if something changed it
            ctx = _Context(media, book, report)
            tracks_out = _compile_tracks(ctx, ctx_tracks, plan_hash)
    project = None
    if report.ok:
        try:
            project = Project(tracks=tuple(timeline_ops.normalize_track(t) for t in tracks_out))
        except TimelineError as exc:  # the checks above should make this unreachable
            report.error(
                "/tracks", "plan.internal", f"the plan could not be laid out: {exc}", "report this plan as a bug"
            )
    return report, project, doc


def _effective_base_revision(top: dict[str, Any], param: int | None, report: PlanReport) -> int | None:
    in_plan = top.get("base_revision")
    if param is not None and in_plan is not None and param != in_plan:
        report.error(
            "/base_revision",
            "plan.base_revision.conflict",
            f"the plan says base_revision {in_plan} but the request says {param}",
            "give the revision once, or make them agree",
        )
    return param if param is not None else in_plan


def _check_mode(
    report: PlanReport,
    mode: str,
    base: int | None,
    unconditional: bool,
    name: str | None,
    exists: bool | None,
    store: ProjectStore | None,
) -> None:
    if mode == "create":
        if base is not None:
            report.error(
                "/base_revision", "plan.mode.field_not_applicable",
                "base_revision only applies to mode \"replace\"", "drop it, or use mode \"replace\"",
            )  # fmt: skip
        if unconditional:
            report.error(
                "/replace_unconditionally", "plan.mode.field_not_applicable",
                "replace_unconditionally only applies to mode \"replace\"", "drop it, or use mode \"replace\"",
            )  # fmt: skip
        if exists:
            report.error(
                "/project", "plan.project.exists", f"project {name!r} already exists",
                "use mode \"replace\" with base_revision (from show_timeline), or pick another name",
            )  # fmt: skip
        return
    if base is None and not unconditional:
        report.error(
            "/base_revision",
            "plan.replace.needs_base_revision",
            "replacing a project needs base_revision (the revision you based the plan on) or replace_unconditionally",
            "read the project's revision with show_timeline and send it as base_revision; "
            'set "replace_unconditionally": true only if losing concurrent edits is acceptable',
        )
    if base is not None and unconditional:
        report.error(
            "/replace_unconditionally", "plan.replace.ambiguous",
            "base_revision and replace_unconditionally contradict each other", "send one of them",
        )  # fmt: skip
    if exists is False:
        report.error(
            "/project", "plan.project.not_found", f"no project named {name!r} to replace",
            "use mode \"create\" to make it",
        )  # fmt: skip
    elif exists and store is not None and name is not None:
        old = store.load_timeline(name)
        count = sum(len(t.clips) for t in old.tracks)
        report.warn(
            "/project", "plan.project.replaces_existing",
            f"replaces {name!r} (revision {old.revision}, {count} clips) wholesale", "",
        )  # fmt: skip


def _compile_tracks(ctx: _Context, tracks: list[Any], plan_hash: str) -> list[Track]:
    report = ctx.report
    if not tracks:
        report.error("/tracks", "plan.tracks.empty", "a plan needs at least one track", "add a video track")
        return []
    if len(tracks) > MAX_TRACKS:
        report.error(
            "/tracks", "plan.tracks.too_many", f"{len(tracks)} tracks; at most {MAX_TRACKS} are allowed",
            "merge tracks, or split the work over several projects",
        )  # fmt: skip
        return []
    total = sum(len(t.get("clips") or []) for t in tracks if isinstance(t, dict) and isinstance(t.get("clips"), list))
    too_many = total > MAX_CLIPS
    if too_many:
        report.error(
            "/tracks", "plan.clips.too_many", f"{total} clips in total; at most {MAX_CLIPS} are allowed",
            "split the plan over several projects",
        )  # fmt: skip

    explicit_tracks: dict[str, str] = {}
    explicit_clips: dict[str, str] = {}
    taken: set[str] = set()  # explicit ids, so generated ones steer clear of them
    for t in tracks:
        if not isinstance(t, dict):
            continue
        taken.update(v for v in [t.get("id")] if isinstance(v, str))
        if isinstance(t.get("clips"), list):
            taken.update(c["id"] for c in t["clips"] if isinstance(c, dict) and isinstance(c.get("id"), str))

    out: list[Track] = []
    seen_video = False
    kind_problem = False
    for ti, raw in enumerate(tracks):
        path = _pointer("tracks", ti)
        if not isinstance(raw, dict):
            report.error(path, "plan.field.type", "a track must be an object", "")
            continue
        spec = _check_object(raw, TRACK_FIELDS, path, report)
        kind = spec.get("kind")
        magnetic = spec.get("magnetic", kind == "video" and not seen_video)
        seen_video = seen_video or kind == "video"
        track_id = _claim_id(spec.get("id"), _pointer("tracks", ti, "id"), explicit_tracks, report) or _generated_id(
            plan_hash, "track", ti, taken=taken
        )
        clips = raw.get("clips")
        items: list[_Item] = []
        if isinstance(clips, list) and kind is not None and not too_many:
            for ci, clip_raw in enumerate(clips):
                items.append(
                    _compile_clip(ctx, clip_raw, _pointer("tracks", ti, "clips", ci), ci, kind, magnetic, items)
                )
        elif clips is not None and not isinstance(clips, list):
            report.error(path + "/clips", "plan.field.type", "'clips' must be an array", "")
        if clips is None or (isinstance(clips, list) and not clips):
            report.warn(path, "plan.track.empty", f"track {ti} has no clips", "")
        if kind is None:
            kind_problem = True
            continue
        # Ids are claimed after the clips are checked, for every clip, so duplicates are found even among clips
        # that have other problems; a generated id depends only on the plan and the position.
        built: list[Clip] = []
        for item in items:
            raw_id = clips[item.index].get("id") if isinstance(clips[item.index], dict) else None
            where = _pointer("tracks", ti, "clips", item.index, "id")
            cid = _claim_id(raw_id, where, explicit_clips, report) or _generated_id(
                plan_hash, "clip", ti, item.index, taken=taken
            )
            if item.clip is not None:
                item.clip = replace(item.clip, id=cid)
                built.append(item.clip)
        if magnetic:
            _check_crossfades(report, ti, items)
        else:
            _check_overlaps(report, ti, items)
        out.append(Track(id=track_id, kind=kind, clips=tuple(built), magnetic=magnetic))
    if not kind_problem and not any(t.kind == "video" for t in out):
        report.error(
            "/tracks",
            "plan.tracks.no_video",
            "a project needs at least one video track",
            'add a track with kind "video"',
        )
    return out


def _claim_id(value: Any, path: str, seen: dict[str, str], report: PlanReport) -> str | None:
    if not isinstance(value, str):
        return None
    if not _ID_RE.match(value):
        report.error(path, "plan.id.invalid", f"id {value!r} may only contain letters, digits, '_', '-' and '.'", "")
        return None
    if value in seen:
        report.error(
            path, "plan.id.duplicate", f"id {value!r} is already used at {seen[value]}",
            "ids must be unique among the clips (and among the tracks); drop them to have them generated",
        )  # fmt: skip
        return None
    seen[value] = path
    return value


def _compile_clip(
    ctx: _Context,
    raw: Any,
    path: str,
    index: int,
    track_kind: str,
    magnetic: bool,
    earlier: list[_Item],
) -> _Item:
    report = ctx.report
    item = _Item(index)
    if not isinstance(raw, dict):
        report.error(path, "plan.field.type", "a clip must be an object", "")
        return item
    before = len(report.errors)
    spec = _check_object(raw, CLIP_FIELDS, path, report)
    if "kind" in raw and "kind" not in spec:
        return item  # an unknown kind was reported; the rest of the clip can't be judged
    kind = spec.get("kind", "media")
    is_text = kind == "text"
    for name in _MEDIA_ONLY if is_text else _TEXT_ONLY:
        if name in raw:
            report.error(
                f"{path}/{name}", "plan.clip.field_not_applicable",
                f"{name!r} does not apply to a {kind} clip", f"drop {name!r}" if is_text else "text clips are kind \"text\"",
            )  # fmt: skip
    in_point = float(spec.get("in", 0.0))
    asset_row: assets.Asset | None = None
    source = ""
    if is_text:
        if track_kind == "audio":
            report.error(
                path,
                "plan.clip.text_on_audio_track",
                "a text clip can't go on an audio track",
                'put titles on a video track with "magnetic": false',
            )
        elif magnetic:
            report.error(
                path,
                "plan.clip.text_on_main_track",
                "text goes on an overlay video track, not the main (magnetic) track",
                'put titles on a video track with "magnetic": false',
            )
        if "text" not in raw or (isinstance(raw["text"], str) and not raw["text"].strip()):
            report.error(path + "/text", "plan.clip.text_required", "a text clip needs non-empty text", 'set "text"')
        if "out" not in raw:
            report.error(
                path + "/out",
                "plan.field.required",
                "a text clip needs `out` (how long the title shows, with `in` 0)",
                'set "out"',
            )
        out_point = spec.get("out")
        limit = float("inf")
    else:
        found = ctx.find_asset(raw, path)
        out_point = spec.get("out")
        limit = None
        if found is not None:
            asset_row, source = found
            limit = asset_row.duration
            if track_kind == "video" and not asset_row.has_video:
                report.error(
                    path,
                    "plan.clip.audio_only_on_video_track",
                    f"{asset_row.path} has no video stream, so it can't go on a video track",
                    "put audio-only assets on an audio track",
                )
            elif track_kind == "audio" and not asset_row.has_audio:
                report.error(
                    path,
                    "plan.clip.no_audio_for_audio_track",
                    f"{asset_row.path} has no audio stream, so it can't go on an audio track",
                    "",
                )
            if out_point is None and "out" not in raw:
                out_point = asset_row.duration
    if out_point is not None and limit is not None:
        item.duration = float(out_point) - in_point
        if out_point <= in_point:
            report.error(
                path + "/out",
                "plan.clip.in_after_out",
                f"out ({out_point:g}s) must be after in ({in_point:g}s)",
                "swap them or fix the values",
            )
        else:
            try:
                timeline_ops.check_range(in_point, float(out_point), limit)
            except timeline_ops.RuleViolation as exc:
                code, where = {
                    "in_negative": ("plan.clip.in_negative", "/in"),
                    "out_past_end": ("plan.clip.out_of_range", "/out"),
                    "too_short": ("plan.clip.too_short", "/out"),
                }[exc.reason]
                hint = f"the asset is {limit:g}s long" if exc.reason == "out_past_end" else ""
                report.error(path + where, code, str(exc), hint)

    transition = spec.get("transition", "cut")
    fade = float(spec.get("transition_duration", 0.0))
    item.transition, item.fade = transition, fade
    if transition == "cut" and fade > 0:
        report.warn(
            path + "/transition_duration",
            "plan.clip.transition_duration_ignored",
            "transition_duration has no effect on a cut",
            "",
        )
    if transition == "crossfade" and not magnetic:
        report.error(
            path + "/transition",
            "plan.clip.crossfade_on_free_track",
            "crossfades are only available on magnetic tracks",
            'use "cut", or make the track magnetic',
        )
    if magnetic:
        if "start" in raw:
            report.error(
                path + "/start",
                "plan.clip.start_on_magnetic_track",
                "this track keeps its clips back to back; `start` is not allowed",
                'drop `start`, or set "magnetic": false on the track',
            )
    else:
        cursor = max(
            (i.start + i.duration for i in earlier if i.start is not None and i.duration is not None), default=0.0
        )
        item.start = float(spec["start"]) if "start" in spec else cursor
    if magnetic:
        item.start = 0.0

    if len(report.errors) == before and item.duration is not None:
        item.clip = Clip(
            id="",
            source=source,
            in_point=in_point,
            out_point=float(out_point),
            asset=asset_row.id if asset_row else "",
            start=item.start or 0.0,
            gain=float(spec.get("gain", 1.0)),
            muted=bool(spec.get("muted", False)),
            transition=transition if magnetic else "cut",
            transition_duration=fade if magnetic and transition == "crossfade" else 0.0,
            x=float(spec.get("x", 0.5)),
            y=float(spec.get("y", 0.85 if is_text else 0.5)),
            scale=float(spec.get("scale", 1.0)),
            opacity=float(spec.get("opacity", 1.0)),
            brightness=float(spec.get("brightness", 0.0)),
            contrast=float(spec.get("contrast", 1.0)),
            saturation=float(spec.get("saturation", 1.0)),
            kind=kind,
            text=spec.get("text", "") if is_text else "",
            font_size=float(spec.get("font_size", 0.08)),
            color=str(spec.get("color", "#ffffff")),
        )
    return item


def _check_crossfades(report: PlanReport, ti: int, items: list[_Item]) -> None:
    """On a magnetic track, a crossfade must fit in the room the neighbouring clips leave (`timeline_ops`' rule)."""
    for i, item in enumerate(items):
        if item.transition != "crossfade" or item.duration is None:
            continue
        prev = items[i - 1] if i else None
        if prev is not None and prev.duration is None:
            continue  # the neighbour has its own problem; its length is unknown
        prev_room = None if prev is None else prev.duration - (prev.fade if prev.transition == "crossfade" else 0.0)
        try:
            # The fade on this clip's far side is checked when that clip's turn comes (as `prev_room` of the next),
            # so each pair is judged once, at the later clip.
            timeline_ops.check_crossfade(item.fade, item.duration, prev_room, 0.0)
        except timeline_ops.RuleViolation as exc:
            code, field_name = {
                "crossfade_first": ("plan.clip.crossfade_first", "transition"),
                "crossfade_duration": ("plan.clip.transition_duration", "transition_duration"),
                "crossfade_room": ("plan.clip.transition_too_long", "transition_duration"),
            }[exc.reason]
            hint = {
                "crossfade_first": 'the first clip has nothing to fade from; use "cut"',
                "crossfade_duration": "set transition_duration above 0",
                "crossfade_room": "shorten the crossfade or lengthen the neighbouring clips",
            }[exc.reason]
            report.error(_pointer("tracks", ti, "clips", item.index, field_name), code, str(exc), hint)


def _check_overlaps(report: PlanReport, ti: int, items: list[_Item]) -> None:
    """On a free track no two clips may overlap (`timeline_ops.normalize_track`'s rule), reported per clip."""
    placed = sorted((i for i in items if i.start is not None and i.duration is not None), key=lambda i: i.start)
    prev: _Item | None = None
    for item in placed:
        if prev is not None and item.start < prev.start + prev.duration - _EPS:
            report.error(
                _pointer("tracks", ti, "clips", item.index, "start"),
                "plan.clip.overlap",
                f"clip would overlap the clip at index {prev.index} on the track (until {prev.start + prev.duration:g}s)",
                "move it later, put it on another track, or shorten the earlier clip",
            )
            continue  # compare the next clip with the last clip that was fine
        prev = item


