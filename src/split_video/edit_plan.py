def validate_plan(
    media: MediaStore, plan_doc: Any, store: ProjectStore | None = None, *, base_revision: int | None = None
) -> PlanReport:
    """Every problem with `plan_doc`, and warnings. Pure: reads the asset table (and with `store`, whether the project
    exists) and writes nothing. `PlanReport.ok` says whether `apply_plan` would accept it."""
    return _compile(media, plan_doc, store, base_revision)[0]


def build_timeline(media: MediaStore, plan_doc: Any) -> Project:
    """The `Project` a valid plan describes (revision 0, ids filled in). `PlanInvalidError` if it is not valid."""
    report, project, _ = _compile(media, plan_doc, None, None)
    if project is None:
        raise PlanInvalidError(report)
    return project


def apply_plan(
    media: MediaStore,
    store: ProjectStore,
    plan_doc: Any,
    *,
    dry_run: bool = False,
    base_revision: int | None = None,
) -> dict[str, Any]:
    """Create or replace the plan's project, atomically, with ONE `save_timeline`; or, with `dry_run`, only report what
    would happen. `base_revision` (an If-Match header, `--base-revision`, the MCP argument) is the revision the plan was
    written against; it may also be in the plan, and the two must agree.

    `PlanInvalidError` (carrying the full report) if the plan has any problem: nothing is created or changed.
    `RevisionConflictError` if the project moved on since `base_revision`: nothing is written either. Mode `create`
    saves with revision 0 expected, so two racing creators cannot both win. Dry-run is not a reservation: the
    `revision` it reports is a prediction."""
    report, project, doc = _compile(media, plan_doc, store, base_revision)
    if project is None or not report.ok:
        raise PlanInvalidError(report)
    name, mode = doc["project"], doc.get("mode", "create")
    base = base_revision if base_revision is not None else doc.get("base_revision")
    expected = 0 if mode == "create" else base  # None: replace_unconditionally
    if dry_run:
        current = store.load_timeline(name).revision if store.timeline_exists(name) else 0
        store_module.check_base_revision("timeline project", name, current, expected)
        revision = current + 1
    else:
        revision = store.save_timeline(name, project, expected)
    return {
        "project": name,
        "revision": revision,
        "action": "created" if mode == "create" else "replaced",
        "dry_run": dry_run,
        "clips": sum(len(t.clips) for t in project.tracks),
        "duration": project.duration,
        "tracks": [{"id": t.id, "kind": t.kind, "clips": len(t.clips), "end": t.end} for t in project.tracks],
        "warnings": [w.to_dict() for w in report.warnings],
        "plan_hash": report.plan_hash,
        **({"meta": doc["meta"]} if "meta" in doc else {}),
    }


def highlights_to_plan(
    highlights: dict[str, Any],
    *,
    project: str,
    mode: str = "create",
    base_revision: int | None = None,
    crossfade: float = 0.0,
    by_rank: bool = False,
) -> dict[str, Any]:
    """A plan that cuts every candidate of a `suggest_highlights` result onto one main video track.

    The candidates' `start` / `end` are asset-relative seconds, so they are the clips' `in` / `out`. They run in
    time order (`by_rank=True`: best first). With `crossfade` seconds each clip but the first fades in; it is
    capped at half the shortest clip so the plan stays valid."""
    candidates = list(highlights["candidates"])
    if not by_rank:
        candidates.sort(key=lambda c: c["start"])
    fade = 0.0
    if crossfade > 0 and len(candidates) > 1:
        fade = round(min(crossfade, min(c["end"] - c["start"] for c in candidates) / 2), 3)
    clips: list[dict[str, Any]] = []
    for i, c in enumerate(candidates):
        clip: dict[str, Any] = {"asset": highlights["asset"], "in": c["start"], "out": c["end"]}
        if fade and i:
            clip.update(transition="crossfade", transition_duration=fade)
        clips.append(clip)
    plan: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "project": project,
        "mode": mode,
        "tracks": [{"kind": "video", "clips": clips}],
    }
    if base_revision is not None:
        plan["base_revision"] = base_revision
    return plan
