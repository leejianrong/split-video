"""Edit plans: build a whole timeline from one JSON document (SPL-49).

An agent that wants a highlights reel should not make dozens of single edits. It writes ONE plan (sources,
in/out, order, transitions, text, tracks), and `apply_plan` creates or replaces the timeline project with it,
atomically: the whole `Project` is built in memory and saved with a single `ProjectStore.save_timeline`, and a
plan with any problem changes nothing. `docs/edit-plan.md` is the contract; `docs/schemas/edit-plan.v1.schema.json`
is its machine-readable form, generated by `schema()` from the same field tables the validator reads, so the two
cannot drift.

    validate_plan(media, plan_doc, store=None) -> PlanReport      pure, collects EVERY problem, writes nothing
    build_timeline(media, plan_doc)            -> Project         pure; `PlanInvalidError` if the plan is invalid
    apply_plan(media, store, plan_doc, *, dry_run=False, base_revision=None) -> dict
    migrate_plan(doc)                          -> dict            older `schema_version`s to the current one
    schema() / schema_json()                                      the JSON Schema (draft 2020-12)
    highlights_to_plan(result, project=...)    -> dict            glue from `suggest_highlights` output

The editing rules are not restated here: ranges, crossfade room and the numeric limits come from `timeline_ops`
(`check_range`, `check_crossfade`, `CLIP_PROPERTY_RANGES`, `FONT_SIZE_RANGE`, `MIN_CLIP`), and the finished tracks go
through `timeline_ops.normalize_track` like every other edit. Problems are `{"path", "code", "message", "hint"}` with
a JSON-pointer path and a stable, namespaced `plan.*` code (see the catalogue in `docs/edit-plan.md`).
"""

